"""Builds docs/ui/before-after.md from the screenshots in docs/ui/before and docs/ui/after."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2] / "docs" / "ui"
OUT = ROOT / "before-after.md"

RESIDENT = [
    ("Home, clear", "home-clear"),
    ("Home, with a restriction", "home-locked"),
    ("Why is this locked?", "why-locked"),
    ("Tier", "tier"),
    ("Education", "education"),
    ("Commissary", "commissary"),
    ("Calls", "calls"),
    ("Reading", "reading"),
    ("Jobs", "jobs"),
    ("Release prep", "reentry"),
    ("Contacts", "contacts"),
    ("Device not paired", "unpaired"),
]
STAFF = [
    ("Sign in", "login"),
    ("Dashboard", "dashboard"),
    ("Roster", "roster"),
    ("Confirmations", "confirmations"),
    ("Appeals", "appeals"),
    ("Welfare", "welfare"),
    ("Config", "config"),
    ("View as resident", "view-as"),
]


def img(path: str) -> str:
    return f"<img src=\"{path}\" width=\"420\" alt=\"{path}\">" if (ROOT / path).exists() else "n/a"


def row(title: str, before: str, after: str) -> str:
    return f"| {title} | {img(before)} | {img(after)} |\n"


lines = [
    "# Before and after\n\n",
    "Before: `docs/ui/before/` (audit of the original UI). After: `docs/ui/after/`. Generated by "
    "`web/ui-audit/make-before-after.py`; the screenshots by `web/ui-audit/shoot.mjs`.\n\n",
    "File names: `<screen>__<language>__<text size>__<viewport>.png` for the resident kiosk, "
    "`<page>__<language>__<viewport>.png` for staff. Every screen exists at 1280x800, 1024x600 and "
    "1920x1080, in English and Spanish, at normal and large text (resident), in both folders, except "
    "the secondary resident screens which are captured at 1280x800 only.\n\n",
    "## Resident kiosk, 1280x800, English, normal text\n\n| Screen | Before | After |\n|---|---|---|\n",
]
for title, name in RESIDENT:
    lines.append(
        row(
            title,
            f"before/resident/{name}__en__normal__1280x800.png",
            f"after/resident/{name}__en__normal__1280x800.png",
        )
    )
lines.append("\n## Resident kiosk, other conditions (after)\n\n| Condition | Screenshot |\n|---|---|\n")
for title, path in [
    ("Spanish, large text, 1024x600", "after/resident/home-locked__es__large__1024x600.png"),
    ("English, large text, 1920x1080", "after/resident/home-locked__en__large__1920x1080.png"),
    ("Night mode, 1280x800", "after/resident/home-locked-night__en__normal__1280x800.png"),
    ("Night mode, Spanish", "after/resident/home-locked-night__es__normal__1280x800.png"),
    ("Education, Spanish, large text, 1024x600", "after/resident/education__es__large__1024x600.png"),
    ("Commissary, Spanish, 1280x800", "after/resident/commissary__es__normal__1280x800.png"),
]:
    lines.append(f"| {title} | {img(path)} |\n")
lines.append("\n## Staff dashboard, 1280x800\n\n| Page | Before | After (English) |\n|---|---|---|\n")
for title, name in STAFF:
    lines.append(
        row(title, f"before/staff/{name}__1280x800.png", f"after/staff/{name}__en__1280x800.png")
    )
lines.append("\n## Staff dashboard in Spanish (after)\n\n| Page | Screenshot |\n|---|---|\n")
for title, name in [("Roster", "roster"), ("Confirmations", "confirmations"), ("Appeals", "appeals")]:
    lines.append(f"| {title} | {img(f'after/staff/{name}__es__1280x800.png')} |\n")
lines.append(
    """
## Notes

- **Why-locked, before:** the original "why is this locked" screenshots opened the calls page instead
  of the lock explanation (wrong URL in the capture script), so that "before" is the calls page.
  The old lock explanation can be seen in the home screen's restriction card.
- **Staff text:** the staff shell, sign-in, roster, confirmations, appeals and the style guide are fully
  translated. Plain labels, headings, buttons, placeholders and options on the other staff pages now
  come from `staff.pages.*` in the i18n files, with Spanish. About 50 pieces of text that sit inside a
  sentence with a variable (for example "Last {n} days, compared with ...") and a number of message
  strings in code were not moved; `node web/ui-audit/count-hardcoded.mjs` lists what is left.
- **Course titles** in Spanish still show some English names. They come from the course files, not
  from the interface.
- **Existing tests changed:** five selectors that looked for the link text "← Back" now look for
  "Back" (the arrow is an icon), and one assertion that looked for the Tailwind class `text-4xl` on
  the kiosk now looks for `--scale:1.5`. Nothing else in the existing specs was edited.
- **One test fails before and after:** `phase11.spec.ts` "video: the camera is on only during the
  call" fails on the pre-overhaul commit too (its 100-character limit on request bodies is tripped by
  the health heartbeat). It is unrelated to the interface.
"""
)
OUT.write_text("".join(lines))
print(OUT)
